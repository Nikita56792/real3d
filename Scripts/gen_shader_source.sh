#!/bin/bash
# Embeds Sources/Real3DCore/Shaders.metal into a Swift string so no resource bundle is needed.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=Sources/Real3DCore/Shaders.metal
OUT=Sources/Real3DCore/ShaderSource.swift
{
  echo "// GENERATED by Scripts/gen_shader_source.sh from Shaders.metal — do not edit."
  echo "enum ShaderSource {"
  echo "    static let metal = #\"\"\""
  cat "$SRC"
  echo "\"\"\"#"
  echo "}"
} > "$OUT"
echo "generated $OUT"
